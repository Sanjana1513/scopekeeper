const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('index.html', 'utf8');
const start = source.indexOf('function changeCost(');
const end = source.indexOf('const costForm', start);
const {changeCost, revisionBalance, scheduleImpact, budgetBalance, warrantyWindow, supportCountdown, bundleQuote} = vm.runInNewContext(source.slice(start, end) + '\n({changeCost, revisionBalance, scheduleImpact, budgetBalance, warrantyWindow, supportCountdown, bundleQuote})');
assert.equal(changeCost(1.5, 0.5, 1500), 3000);
assert.equal(changeCost(0, 0, 1500), 0);
assert.equal(revisionBalance(3, 1), '2 included round(s) left.');
assert.equal(revisionBalance(2, 2), 'No included revision rounds left.');
assert.equal(revisionBalance(2, 3), '1 round(s) over the agreed limit.');
const impact = scheduleImpact(9, 8, '2026-11-30', '2026-12-01');
assert.equal(impact.delay, 2);
assert.equal(impact.projected, '2026-12-02');
assert.equal(impact.lateBy, 1);
assert.equal(scheduleImpact(0, 8, '2026-12-01', '2026-12-01').lateBy, 0);
assert.equal(budgetBalance(8, 2).progress, 0.25);
assert.equal(budgetBalance(8, 10).message, '2 hours over budget.');
assert.equal(budgetBalance(0, 0).progress, 0);
assert.match(warrantyWindow('2026-11-01', '2026-11-07', '2026-11-07'), /inside/);
assert.match(warrantyWindow('2026-11-01', '2026-11-07', '2026-11-08'), /after/);
assert.match(warrantyWindow('2026-11-01', '2026-11-07', '2026-10-31'), /predates/);
assert.match(warrantyWindow('2026-11-08', '2026-11-07', '2026-11-08'), /end must/);
assert.equal(supportCountdown('2026-11-07', '2026-11-10', '2026-11-06'), 'Support starts in 1 day(s).');
assert.equal(supportCountdown('2026-11-07', '2026-11-10', '2026-11-10'), 'Support ends today.');
assert.equal(supportCountdown('2026-11-07', '2026-11-10', '2026-11-11'), 'Support ended 1 day(s) ago.');
const quote = bundleQuote('1500\n1000', 10, 25);
assert.equal(quote.total, 225000);
assert.equal(quote.deposit, 56250);
assert.equal(quote.balance, 168750);
assert.equal(bundleQuote('0.10\n0.20', 0, 0).total, 30);
assert.equal(bundleQuote('100', 100, 25).deposit, 0);
assert.throws(() => bundleQuote('₹100', 0, 0), /item amounts/);
console.log('Planning calculator assertions passed.');
