const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('index.html', 'utf8');
const start = source.indexOf('function replyVariants(');
const end = source.indexOf('function show(', start);
const variants = vm.runInNewContext(source.slice(start, end) + '\nreplyVariants');
const item = {verdict:'Billable', estimate:'₹3,000', reply:'Thanks for your request.'};
const reply = variants(item, 'Website quote');
assert.match(reply.Email, /^Subject: Website quote\n/);
assert.match(reply.WhatsApp, /^Hi!/);
assert.match(reply.Short, /₹3,000/);
assert.match(reply['Two options'], /1\. Add this work at an estimated ₹3,000/);
assert.match(reply['Two options'], /2\. Continue with the original scope/);
assert.match(variants({...item, estimate:'Estimate pending'}, 'Quote')['Two options'], /after we agree on an estimate/);
assert.equal(variants({...item, verdict:'Included'}, 'Update')['Two options'], undefined);
assert.match(reply['Scope negotiation'], /Reduce[\s\S]+Defer[\s\S]+Add the work at an estimated ₹3,000/);
assert.match(reply['Small request response'], /small change/);
assert.match(reply['Optional extra quote'], /estimated ₹3,000/);
const pending = variants({...item, estimate:'Estimate pending'}, 'Quote');
assert.equal(pending['Optional extra quote'], undefined);
assert.doesNotMatch(pending['Scope negotiation'], /₹/);
assert.equal(variants({...item, verdict:'Included'}, 'Update')['Scope negotiation'], undefined);
const tone = vm.runInNewContext(source.slice(start, end) + '\napplyReplyTone');
assert.equal(tone(reply.Short, 1), reply.Short);
assert.match(tone(reply.Short, 2), /^Thanks for asking/);
assert.match(tone(reply.Email, 0), /^Subject: Website quote\n\nHello/);
assert.match(tone(reply['Optional extra quote'], 0), /₹3,000/);
const match = vm.runInNewContext(source.slice(start, end) + '\nmatchingTemplates');
assert.equal(JSON.stringify(match(reply, '  optional EXTRA quote ')), '["Optional extra quote"]');
assert.equal(JSON.stringify(match(reply, 'nonexistent template')), '[]');
assert.ok(match(reply, '₹3,000').includes('Two options'));
assert.ok(match(reply, '').includes('Standard'));
const coverage = vm.runInNewContext(source.slice(start, end) + '\nevidenceStrength');
assert.equal(coverage({deciding:null, evidence:[]}).level, 0);
assert.equal(coverage({deciding:null, evidence:[{source:'courtesy'}]}).level, 1);
assert.equal(coverage({deciding:'agreement', evidence:[{source:'agreement'}]}).level, 2);
const label = vm.runInNewContext(source.slice(start, end) + '\nassessmentLabel');
assert.equal(label([{verdict:'Included'}, {verdict:'Billable'}]), 'Partially included · other work billable');
assert.equal(label([{verdict:'Billable'}, {verdict:'Billable'}]), 'Billable');
const support = vm.runInNewContext(source.slice(start, end) + '\n({decidingSentence, supportExplanation})');
const agreement = {source:'agreement', text:'The project covers a five-page website with a contact form. Online payments and checkout are excluded.'};
const billable = {verdict:'Billable', deciding:'agreement', evidence:[agreement]};
assert.equal(support.decidingSentence(billable, agreement), 'Online payments and checkout are excluded.');
assert.equal(support.decidingSentence(billable, {...agreement, source:'other'}), '');
assert.match(support.supportExplanation(billable), /Direct support/);
assert.match(support.supportExplanation({verdict:'Needs Review', reason:'Approval missing.'}), /Undetermined.*Approval missing/);
console.log('Reply format assertions passed.');
